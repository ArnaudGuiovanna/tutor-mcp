//! Exercise the same discovery, launch, and RPC modules as the desktop app.
//! This probe deliberately does not prompt a model or print authentication data.

use std::path::{Path, PathBuf};

use serde_json::{json, Value};
use tokio::sync::mpsc;
use tutor_client::acp::AcpClient;
use tutor_client::discovery::{agent_cwd, discover_agents, launch_spec};
use tutor_client::launch::LaunchSpec;

#[derive(Debug, Default, PartialEq)]
struct Options {
    environment: String,
    distribution: Option<String>,
    adapter: Option<String>,
    codex: Option<String>,
    cwd: Option<String>,
    tutor: Option<PathBuf>,
    report: Option<PathBuf>,
}

impl Options {
    fn parse(args: impl IntoIterator<Item = String>) -> Result<Self, String> {
        let mut options = Self {
            environment: "native".into(),
            ..Self::default()
        };
        let mut args = args.into_iter();
        while let Some(key) = args.next() {
            if key == "--help" || key == "-h" {
                return Err("Usage: tutor-client-qualify [--environment native|wsl] [--distribution Ubuntu] [--adapter ABSOLUTE_PATH] [--codex ABSOLUTE_CLI_PATH] [--cwd DIRECTORY] [--tutor NATIVE_TUTOR_BINARY] [--report FILE]".into());
            }
            let value = args
                .next()
                .filter(|value| !value.starts_with("--"))
                .ok_or_else(|| format!("Valeur manquante pour {key}."))?;
            match key.as_str() {
                "--environment" => options.environment = value,
                "--distribution" => options.distribution = Some(value),
                "--adapter" => options.adapter = Some(value),
                "--codex" => options.codex = Some(value),
                "--cwd" => options.cwd = Some(value),
                "--tutor" => options.tutor = Some(value.into()),
                "--report" => options.report = Some(value.into()),
                _ => return Err(format!("Option inconnue : {key}.")),
            }
        }
        if !matches!(options.environment.as_str(), "native" | "wsl") {
            return Err("L’environnement doit être native ou wsl.".into());
        }
        if options.environment == "wsl" && options.distribution.is_none() {
            return Err("Sélectionnez explicitement une distribution avec --distribution.".into());
        }
        if options.environment == "native" && options.distribution.is_some() {
            return Err("--distribution concerne uniquement WSL.".into());
        }
        Ok(options)
    }
}

struct TemporaryDirectory(PathBuf);

impl TemporaryDirectory {
    fn create() -> Result<Self, String> {
        let path = std::env::temp_dir().join(format!(
            "tutor-client-qualification-{}",
            uuid::Uuid::new_v4()
        ));
        #[cfg(unix)]
        let result = {
            use std::os::unix::fs::DirBuilderExt;
            std::fs::DirBuilder::new().mode(0o700).create(&path)
        };
        #[cfg(not(unix))]
        let result = std::fs::create_dir(&path);
        result.map_err(|error| format!("Création du dossier temporaire impossible : {error}"))?;
        Ok(Self(path))
    }
}

impl Drop for TemporaryDirectory {
    fn drop(&mut self) {
        // The path is generated by create(), never accepted from the command
        // line. No existing Tutor data or Codex home can be removed here.
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

#[tokio::main]
async fn main() {
    let options = match Options::parse(std::env::args().skip(1)) {
        Ok(options) => options,
        Err(message) => {
            eprintln!("{message}");
            std::process::exit(2);
        }
    };
    match qualify(&options).await {
        Ok(report) => {
            let text = serde_json::to_string_pretty(&report).expect("JSON qualification report");
            if let Some(path) = &options.report {
                if let Err(error) = std::fs::write(path, format!("{text}\n")) {
                    eprintln!("Impossible d’enregistrer le rapport : {error}");
                    std::process::exit(1);
                }
            }
            println!("{text}");
        }
        Err(message) => {
            eprintln!("Qualification incomplète : {message}");
            std::process::exit(1);
        }
    }
}

async fn qualify(options: &Options) -> Result<Value, String> {
    let targets = discover_agents().await;
    let mut target = targets.into_iter().find(|target| {
        target.environment == options.environment &&
            options.distribution.as_ref().is_none_or(|name| target.distribution.as_ref() == Some(name))
    }).ok_or("Aucune installation ne correspond à cet environnement. Vérifiez la distribution et relancez la détection.")?;
    if let Some(adapter) = &options.adapter {
        target.adapter_path = Some(adapter.clone());
        target.available = true;
    }
    if let Some(codex) = &options.codex {
        target.id = "manual".into();
        target.codex_path = Some(codex.clone());
    }
    let temporary = TemporaryDirectory::create()?;
    let cwd = options.cwd.clone().unwrap_or_else(|| {
        if options.environment == "wsl" {
            "~".into()
        } else {
            temporary.0.to_string_lossy().into_owned()
        }
    });
    let resolved_cwd = agent_cwd(&target, &cwd).await?;
    let mut spec = launch_spec(&target, &cwd).await?;
    if options.environment == "native" {
        // Native CI never touches the developer's Codex configuration/login.
        let home = temporary.0.join("codex-home");
        std::fs::create_dir(&home)
            .map_err(|_| "Impossible de préparer le profil Codex temporaire.")?;
        spec.env
            .push(("CODEX_HOME".into(), home.to_string_lossy().into_owned()));
    }
    let (events, mut received) = mpsc::unbounded_channel();
    let drain = tokio::spawn(async move { while received.recv().await.is_some() {} });
    let client = AcpClient::spawn(spec, events).await?;
    let response = client.request("initialize", json!({
        "protocolVersion":1, "clientCapabilities":{},
        "clientInfo":{"name":"tutor-client-qualification","version":env!("CARGO_PKG_VERSION")}
    })).await;
    let stopped = client.stop().await;
    drain.abort();
    let response = response?;
    stopped?;
    if response["protocolVersion"] != 1 || !response["agentCapabilities"].is_object() {
        return Err("L’adaptateur n’a pas négocié le contrat ACP pris en charge.".into());
    }
    let agent = response
        .get("agentInfo")
        .ok_or("L’adaptateur n’a pas annoncé sa version.")?;
    let name = agent
        .get("name")
        .and_then(Value::as_str)
        .unwrap_or_default();
    let version = agent
        .get("version")
        .and_then(Value::as_str)
        .unwrap_or_default();
    if !name.contains("codex") || version.is_empty() {
        return Err("La réponse ne permet pas d’identifier un adaptateur Codex versionné.".into());
    }
    let tutor = if let Some(binary) = &options.tutor {
        qualify_tutor(binary, &temporary.0).await?
    } else {
        json!({"tested":false, "reason":"Aucun binaire Tutor fourni avec --tutor."})
    };
    Ok(json!({
        "contractVersion":1,
        "host":std::env::consts::OS,
        "environment":target.environment,
        "distribution":target.distribution,
        "wslUser":target.wsl_user,
        "adapterPath":target.adapter_path,
        "codexPath":target.codex_path,
        "codexRuntime":if options.codex.is_some() { "explicit-cli" } else { "adapter-bundled" },
        "agentCwd":resolved_cwd,
        "agent":{"name":name,"version":version},
        "protocolVersion":response["protocolVersion"],
        "supportsHttpMcp":response.pointer("/agentCapabilities/mcpCapabilities/http").and_then(Value::as_bool).unwrap_or(false),
        "supportsSessionLoad":response.pointer("/agentCapabilities/loadSession").and_then(Value::as_bool).unwrap_or(false),
        "launchInitializeStop":"passed",
        "tutor":tutor,
        "modelPromptTested":false,
        "desktopUiTested":false,
        "scope":"Discovery, actual ACP initialize and process shutdown; optional direct native Tutor MCP persistence. No model-generated tutoring is claimed."
    }))
}

async fn open_tutor(binary: &Path, directory: &Path) -> Result<AcpClient, String> {
    let binary = binary
        .canonicalize()
        .map_err(|_| "Le binaire Tutor est introuvable.")?;
    let (events, mut received) = mpsc::unbounded_channel();
    tokio::spawn(async move { while received.recv().await.is_some() {} });
    let client = AcpClient::spawn(
        LaunchSpec {
            program: binary.to_string_lossy().into_owned(),
            args: vec![
                "--local".into(),
                "--data-dir".into(),
                directory.to_string_lossy().into_owned(),
            ],
            env: vec![],
            // Let Tutor create its profile with its own private permissions
            // and Windows ACL. A precreated default-mode directory is refused.
            cwd: Some(directory.parent().unwrap_or(directory).to_path_buf()),
        },
        events,
    )
    .await?;
    let initialized = client
        .request(
            "initialize",
            json!({
                "protocolVersion":"2025-11-25", "capabilities":{},
                "clientInfo":{"name":"tutor-client-qualification","version":"0.1.0"}
            }),
        )
        .await;
    if let Err(error) = initialized {
        let _ = client.stop().await;
        return Err(format!(
            "Le serveur Tutor n’a pas terminé l’initialisation MCP : {error}"
        ));
    }
    client
        .notify("notifications/initialized", json!({}))
        .await?;
    Ok(client)
}

async fn call_tool(client: &AcpClient, name: &str, arguments: Value) -> Result<Value, String> {
    let result = client
        .request("tools/call", json!({"name":name,"arguments":arguments}))
        .await?;
    if result
        .get("isError")
        .and_then(Value::as_bool)
        .unwrap_or(false)
    {
        return Err(format!("Tutor a refusé l’outil {name}."));
    }
    if let Some(structured) = result.get("structuredContent") {
        return Ok(structured.clone());
    }
    result
        .get("content")
        .and_then(Value::as_array)
        .and_then(|content| {
            content
                .iter()
                .find_map(|block| block.get("text").and_then(Value::as_str))
        })
        .and_then(|text| serde_json::from_str(text).ok())
        .ok_or_else(|| format!("La réponse de {name} n’est pas structurée."))
}

async fn qualify_tutor(binary: &Path, temporary: &Path) -> Result<Value, String> {
    let directory = temporary.join("tutor-profile");
    let client = open_tutor(binary, &directory).await?;
    let first = async {
        let list = client.request("tools/list", json!({})).await?;
        let tools = list.get("tools").and_then(Value::as_array).ok_or("Inventaire d’outils Tutor absent.")?;
        for required in ["init_domain", "get_learner_context", "start_learning_session"] {
            if !tools.iter().any(|tool| tool["name"] == required) {
                return Err(format!("L’outil Tutor {required} est absent."));
            }
        }
        let arguments = json!({"name":"Qualification du client — astronomie",
            "concepts":["Observer le ciel"],"prerequisites":{},
            "personal_goal":"Comprendre une observation simple.","idempotency_key":"client-qualification-domain-1"});
        let created = call_tool(&client, "init_domain", arguments.clone()).await?;
        let replay = call_tool(&client, "init_domain", arguments).await?;
        let domain = created.get("domain_id").and_then(Value::as_str).filter(|id| !id.is_empty())
            .ok_or("Tutor n’a pas enregistré de formation.")?.to_string();
        if replay["domain_id"] != domain {
            return Err("Le rejeu a créé une autre formation.".into());
        }
        let session = call_tool(&client,"start_learning_session",json!({
            "domain_id":domain,"idempotency_key":"client-qualification-session-1"})).await?;
        let session = session.get("session_id").and_then(Value::as_str).filter(|id| !id.is_empty())
            .ok_or("Tutor n’a pas enregistré de séance.")?.to_string();
        Ok::<_,String>((domain,session,tools.len()))
    }.await;
    let stopped = client.stop().await;
    let (domain, session, tool_count) = first?;
    stopped?;
    let resumed = open_tutor(binary, &directory).await?;
    let context = call_tool(&resumed, "get_learner_context", json!({"domain_id":domain})).await;
    let stopped = resumed.stop().await;
    let context = context?;
    stopped?;
    let domains = context
        .get("domains")
        .and_then(Value::as_array)
        .ok_or("Formations absentes après reprise.")?;
    if domains.len() != 1 || domains[0]["domain_id"] != domain || context["session_id"] != session {
        return Err("La formation et la séance ne sont pas retrouvées à la reprise.".into());
    }
    Ok(
        json!({"tested":true,"environment":"native","transport":"stdio",
        "toolCount":tool_count,"formationCreated":true,"idempotentReplay":true,
        "sessionOpened":true,"persistentRestart":"passed",
        "scope":"Direct MCP from the client transport; no Codex tool invocation or assessment is claimed."}),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[cfg(unix)]
    #[test]
    fn qualification_profiles_start_from_a_private_temporary_directory() {
        use std::os::unix::fs::PermissionsExt;
        let directory = TemporaryDirectory::create().unwrap();
        assert_eq!(
            std::fs::metadata(&directory.0)
                .unwrap()
                .permissions()
                .mode()
                & 0o777,
            0o700
        );
        // Tutor must create this child itself, using privatefs for Unix modes
        // or Windows ACLs. Default-mode precreation makes its startup fail.
        assert!(!directory.0.join("tutor-profile").exists());
    }

    #[test]
    fn wsl_requires_an_explicit_distribution() {
        assert!(Options::parse(["--environment".into(), "wsl".into()]).is_err());
        let options = Options::parse(
            [
                "--environment",
                "wsl",
                "--distribution",
                "Ubuntu Dev",
                "--cwd",
                "/home/user/mes cours",
            ]
            .into_iter()
            .map(str::to_string),
        )
        .unwrap();
        assert_eq!(options.distribution.as_deref(), Some("Ubuntu Dev"));
        assert_eq!(options.cwd.as_deref(), Some("/home/user/mes cours"));
    }

    #[test]
    fn rejects_unknown_flags_and_missing_values() {
        assert!(Options::parse(["--unknown".into(), "value".into()]).is_err());
        assert!(Options::parse(["--adapter".into()]).is_err());
        assert!(Options::parse(["--environment".into(), "other".into()]).is_err());
        assert!(Options::parse(["--distribution".into(), "Ubuntu".into()]).is_err());
    }
}
